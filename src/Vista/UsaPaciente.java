    public String filtrarPacientes(ArrayList<Paciente> bd, int edadDada) {
    StringBuilder resultado = new StringBuilder();
    resultado.append("Los pacientes solicitados son:\n");
    
    for (Paciente p : bd) {
        if (p.getEdad() > edadDada) {
            resultado.append("Nombre: ").append(p.getNombre())
                     .append(" - Edad: ").append(p.getEdad())
                     .append(" - Efectividad: ").append(p.calcularEfectividad());
            
            if (p instanceof PacienteAmbulatorio) {
                PacienteAmbulatorio pa = (PacienteAmbulatorio) p;
                resultado.append(" - Días en casa: ").append(pa.getDiasCasa());
            }
            resultado.append("\n");
        }
    }
    
    return resultado.toString();
}
        

