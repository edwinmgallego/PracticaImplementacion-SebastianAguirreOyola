    private void ejecutarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ejecutarReporteActionPerformed
        try {
        
        String inputEdad = javax.swing.JOptionPane.showInputDialog(this, "Ingrese la edad dada:");
        
        if (inputEdad != null && !inputEdad.trim().isEmpty()) {
            int edadDada = Integer.parseInt(inputEdad);
            
            
            String reporte = filtrarPacientes(losPacientes, edadDada);
            
           
            jTextArea1.setText(reporte);
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error: Debe ingresar un número entero válido.");
    }
    }//GEN-LAST:event_ejecutarReporteActionPerformed

    private void insertarPacienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_insertarPacienteActionPerformed
        try {
        
        String nombre = jTextField1.getText();
        String diaIngreso = jTextField2.getText();
        int edad = Integer.parseInt(jTextField3.getText());
        
        String nombreMed = jTextField4.getText();
        double dosisMed = Double.parseDouble(jTextField5.getText());
        
        Medicamento suMedicamento = new Medicamento(nombreMed, dosisMed);
        
        String tipoPaciente = jComboBox1.getSelectedItem().toString();
        
        if (tipoPaciente.equalsIgnoreCase("Hospitalizado")) {

            double peso = Double.parseDouble(jTextField6.getText());
            
            PacienteHospitalizado ph = new PacienteHospitalizado(nombre, diaIngreso, edad, suMedicamento, peso);
            losPacientes.add(ph);
            
        } else if (tipoPaciente.equalsIgnoreCase("Ambulatorio")) {
            
            int diasCasa = Integer.parseInt(jTextField7.getText());
            
            PacienteAmbulatorio pa = new PacienteAmbulatorio(nombre, diaIngreso, edad, suMedicamento, diasCasa);
            losPacientes.add(pa);
        }
        
        javax.swing.JOptionPane.showMessageDialog(this, "Paciente insertado correctamente.");
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error: Por favor verifica que los campos numéricos tengan valores válidos.");
    }
    }//GEN-LAST:event_insertarPacienteActionPerformed

